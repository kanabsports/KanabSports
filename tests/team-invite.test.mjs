import assert from 'node:assert/strict';
import {teamInvite} from '../assets/team-invite-copy.mjs';
import {onRequestGet as redirect} from '../functions/join/[code].js';
const coach={name:'Jordan Smith',team:'Kanab Girls Basketball',sport:'Basketball',role:'Head Coach',teamCode:'KS-ABC123'};
const head=teamInvite(coach,'https://kanabsports.com');
const assistant=teamInvite({...coach,name:'Alex Jones',role:'Assistant Coach'},'https://kanabsports.com');
assert.equal(head.url,assistant.url);
assert.match(head.message,/Coach Jordan Smith with Kanab Girls Basketball/);
assert.match(assistant.message,/Assistant Coach Alex Jones/);
assert.doesNotMatch(assistant.message,/Jordan Smith/);
assert.equal((head.message.match(/Basketball/g)||[]).length,1);
assert.match(head.message,/No app download needed/);
assert.match(head.message,/may require approval/);
assert.throws(()=>teamInvite({...coach,teamCode:'../admin'},'https://kanabsports.com'));
const result=redirect({request:new Request('https://kanabsports.com/join/KS-ABC123'),params:{code:'KS-ABC123'}});
assert.equal(result.status,302);
assert.equal(result.headers.get('Location'),'https://kanabsports.com/family/?code=KS-ABC123');
assert.equal(redirect({request:new Request('https://kanabsports.com/join/bad'),params:{code:'https://evil.test'}}).status,400);
console.log('Team invitation copy and join redirect passed');
